#!/usr/bin/env python3
"""Local Compose backup and isolated restore drill. Never restores over the source DB."""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import uuid
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCKER = shutil.which("docker") or "/Applications/Docker.app/Contents/Resources/bin/docker"
BASE = [DOCKER, "compose", "exec", "-T", "db"]
TABLES = [
    "accounts_user",
    "accounts_membership",
    "organizations_organizationalunit",
    "commitments_commitmentdefinition",
    "commitments_commitmentoccurrence",
    "commitments_commitmentassignment",
    "commitments_occurrenceversion",
    "commitments_actionrecord",
    "commitments_evidence",
    "commitments_evidenceblob",
    "commitments_evidencewithdrawal",
    "commitments_workflowtransition",
    "commitments_recurrenceversion",
    "customfields_formversion",
    "reports_reportfavorite",
]


def command(script, db=None, **kwargs):
    args = BASE + ["sh", "-c", script, "phase8"] + ([db] if db else [])
    return subprocess.run(args, cwd=ROOT, stderr=subprocess.PIPE, **kwargs)


def sql(query, db=None):
    # Database is generated by this program; SQL is a fixed internal template.
    script = (
        'exec psql -X -v ON_ERROR_STOP=1 -At -U "$POSTGRES_USER" -d "${1:-$POSTGRES_DB}" -c "$2"'
    )
    result = subprocess.run(
        BASE + ["sh", "-c", script, "phase8", db or "", query],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if result.returncode:
        raise RuntimeError("Falha na consulta de verificação; nenhum dado foi impresso.")
    return result.stdout.decode().strip()


def fingerprints(db=None):
    result = {}
    for table in TABLES:
        value = sql(
            f"SELECT count(*)::text || ':' || coalesce(md5(string_agg(md5(row_to_json(t)::text),'' ORDER BY md5(row_to_json(t)::text))),'empty') FROM {table} t",
            db,
        )
        count, digest = value.split(":")
        result[table] = {"count": int(count), "fingerprint": digest}
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--directory", type=Path, default=ROOT / ".backups")
    parser.add_argument("--restore-check", action="store_true")
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(args.directory, 0o700)
    stem = (
        "agenda-"
        + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        + "-"
        + uuid.uuid4().hex[:8]
    )
    path = args.directory / (stem + ".dump")
    before = fingerprints() if args.restore_check else None
    with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb") as output:
        result = command('exec pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc', stdout=output)
    if result.returncode:
        path.unlink()
        raise RuntimeError("pg_dump falhou; arquivo incompleto removido.")
    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "restore_checked": False,
    }
    if args.restore_check:
        target = "phase8_restore_" + uuid.uuid4().hex
        if not re.fullmatch(r"phase8_restore_[0-9a-f]{32}", target):
            raise RuntimeError("Destino de recuperação recusado.")
        created = False
        try:
            result = command(
                'exec createdb -U "$POSTGRES_USER" "$1"', target, stdout=subprocess.PIPE
            )
            if result.returncode:
                raise RuntimeError("Não foi possível criar a base descartável; fonte preservada.")
            created = True
            with path.open("rb") as source:
                result = command(
                    'exec pg_restore --exit-on-error --no-owner --no-acl -U "$POSTGRES_USER" -d "$1"',
                    target,
                    stdin=source,
                    stdout=subprocess.PIPE,
                )
            if result.returncode:
                raise RuntimeError("Restauração descartável falhou; fonte preservada.")
            restored = fingerprints(target)
            after = fingerprints()
            stable = [t for t in TABLES if before[t] == after[t]]
            if any(restored[t] != before[t] for t in stable):
                raise RuntimeError("Fingerprint de tabela estável divergiu após restauração.")
            protections = int(
                sql(
                    "SELECT count(*) FROM pg_trigger WHERE tgname='protect_history' AND NOT tgisinternal",
                    target,
                )
            )
            if protections < 8:
                raise RuntimeError("Proteção de histórico não restaurada.")
            probe = command(
                'exec psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$1" -c "UPDATE audit_auditevent SET reason=reason WHERE id=(SELECT id FROM audit_auditevent LIMIT 1)"',
                target,
                stdout=subprocess.PIPE,
            )
            if int(sql("SELECT count(*) FROM audit_auditevent", target)) and (
                probe.returncode == 0 or b"Historical records are append-only" not in probe.stderr
            ):
                raise RuntimeError("Teste de imutabilidade não passou na cópia.")
            invalid_evidence = int(
                sql(
                    "SELECT count(*) FROM commitments_evidence e LEFT JOIN commitments_evidenceblob b ON replace(b.id::text, '-', '')=e.storage_key WHERE e.storage_backend='apps.commitments.evidence_storage.DatabaseEvidenceStorage' AND (b.id IS NULL OR octet_length(b.content)<>e.size OR encode(sha256(b.content),'hex')<>e.sha256)",
                    target,
                )
            )
            if invalid_evidence:
                raise RuntimeError(
                    "Integridade de evidência restaurada divergiu do hash registrado."
                )
            manifest.update(
                restore_checked=True,
                restored_tables=restored,
                stable_tables_compared=len(stable),
                stable_tables=stable,
                evidence_integrity_checked=True,
                history_triggers=protections,
            )
        finally:
            if created:
                result = command(
                    'exec dropdb -U "$POSTGRES_USER" "$1"', target, stdout=subprocess.PIPE
                )
                if result.returncode:
                    raise RuntimeError("Remover manualmente somente a base descartável " + target)
    manifest_path = args.directory / (stem + ".json")
    with os.fdopen(
        os.open(manifest_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w"
    ) as output:
        json.dump(manifest, output, indent=2)
    print(
        json.dumps(
            {
                "backup": str(path),
                "manifest": str(manifest_path),
                "bytes": manifest["bytes"],
                "restore_checked": manifest["restore_checked"],
            }
        )
    )


if __name__ == "__main__":
    main()
